"""
run42_esd.py -- what IS the smooth spectral density of the compression?

Run 29 compared the empirical spectral distribution (ESD) of the compressed
observable with the SEMICIRCLE law, found ratios rho_m/Catalan_m = {3.6,15,64}
and concluded that the compression is not random-matrix like ("critical
negative finding"), which is what drove the pessimistic bottom line of runs
29-40.  Two things are checked here.

  (i)  Run 29 used  B = v[:,idxs]  with v from `numpy.linalg.eig` on a UNITARY
       matrix with degenerate eigenvalues.  Those columns are NOT orthonormal,
       so B^dagger V B is not the compression.  We quantify the damage.
  (ii) Theorem T6/T8 predicts the ESD of the compression to be the spectral
       distribution of Vbar = K^{-1} sum_j U^j V U^{-j} on the FULL space
       (semiclassically: the value distribution of the classical K-step
       Birkhoff average), NOT the semicircle law.  We test that prediction.

Outputs artifacts/run42_esd.json.
"""
import json
import math
import os
import sys
from math import comb

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bgs_core as bc                                            # noqa: E402

ART = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "artifacts")
FREQS = [(1, 0), (0, 1), (1, 1), (1, -1), (2, 0), (0, 2), (2, 1), (1, 2)]


def catalan(n):
    return comb(2 * n, n) // (n + 1)


def double_factorial_odd(n):
    """(2n-1)!! = moments of the standard Gaussian."""
    out = 1
    for j in range(1, n + 1):
        out *= (2 * j - 1)
    return out


def ks(a, b):
    """Two-sample Kolmogorov-Smirnov distance."""
    a = np.sort(np.asarray(a, dtype=float))
    b = np.sort(np.asarray(b, dtype=float))
    allv = np.concatenate([a, b])
    Fa = np.searchsorted(a, allv, side="right") / len(a)
    Fb = np.searchsorted(b, allv, side="right") / len(b)
    return float(np.max(np.abs(Fa - Fb)))


def symmetric_coeffs(freqs, R, N, rng, mode):
    """Real Weyl coefficients.  mode='sym': invariant under n -> R^T n (i.e.
    [Theta,V]=0);  mode='gen': independent coefficients (no R-symmetry)."""
    RT = np.array([[R[0], R[2]], [R[1], R[3]]], dtype=np.int64)
    labels = set()
    for (n1, n2) in freqs:
        labels.add((n1 % N, n2 % N))
        labels.add(((-n1) % N, (-n2) % N))
    coeffs = {}
    if mode == "gen":
        done = set()
        for lab in sorted(labels):
            if lab in done:
                continue
            neg = ((-lab[0]) % N, (-lab[1]) % N)
            c = float(rng.standard_normal())
            coeffs[lab] = c
            coeffs[neg] = c
            done.update({lab, neg})
        return coeffs
    # sym: orbits under the group generated by -I and R^T
    done = set()
    for lab in sorted(labels):
        if lab in done:
            continue
        orb, stack = set(), [lab]
        while stack:
            cur = stack.pop()
            if cur in orb:
                continue
            orb.add(cur)
            v = np.array(cur, dtype=np.int64)
            for w in ((RT @ v) % N, (-v) % N):
                stack.append((int(w[0]) % N, int(w[1]) % N))
        c = float(rng.standard_normal())
        for o in orb:
            coeffs[o] = c
        done |= orb
    return coeffs


def rtilde(levels):
    """Unfolding-free consecutive-spacing-ratio statistic (Atas et al. 2013):
    r_i = s_{i+1}/s_i,  rtilde = min(r,1/r).  Reference means:
    Poisson 0.38629, GOE 0.53590, GUE 0.59946, GSE 0.67617."""
    x = np.sort(np.asarray(levels, dtype=float))
    s = np.diff(x)
    s = s[s > 0]
    if len(s) < 3:
        return np.array([])
    r = s[1:] / s[:-1]
    return np.minimum(r, 1.0 / r)


def moments_report(M):
    """rho_m = Tr(M^{2m})/m/sigma^{2m}, sigma^2 = Tr(M^2)/m, vs Catalan and
    Gaussian (2m-1)!!.  M must be Hermitian and traceless."""
    m = M.shape[0]
    M = M - np.trace(M) / m * np.eye(m)
    tr2 = float(np.real(np.trace(M @ M)))
    s2 = tr2 / m
    rows = {}
    P = M @ M
    cur = P.copy()
    for mm in range(1, 5):
        tr = float(np.real(np.trace(cur)))
        rho = tr / m / (s2 ** mm)
        rows[mm] = dict(rho=rho, catalan=catalan(mm), gauss=double_factorial_odd(mm),
                        ratio_cat=rho / catalan(mm),
                        ratio_gauss=rho / double_factorial_odd(mm))
        cur = cur @ P
    return dict(sigma2=s2, rows=rows)


def analyse(A, N, seed=1, mode="gen"):
    U = bc.U_cat(A, N)
    k, sign, K = bc.mat_order(A, N)
    chi, tres = bc.torsion_certificate(U, K)
    AT = np.array([[A[0], A[2]], [A[1], A[3]]], dtype=np.int64)
    Rs = bc.reversing_involution(A)
    R = Rs[0]
    rng = np.random.default_rng(seed)
    coeffs = symmetric_coeffs(FREQS, R, N, rng, mode)
    cbar = bc.birkhoff_average(coeffs, AT, K, N)

    Id = np.eye(N, dtype=complex)
    Vbar = bc.weyl_sum_operator(cbar, N, Id)
    Vbar = 0.5 * (Vbar + Vbar.conj().T)
    full = np.linalg.eigvalsh(Vbar)

    # Theta check
    UM, M = bc.theta_operator(A, N, R)
    V = bc.weyl_sum_operator(coeffs, N, Id)
    thV = bc.theta_conjugate(UM, V)
    theta_dev = float(np.max(np.abs(thV - V)))

    out = dict(A=list(A), N=N, k=k, K=K, mode=mode, seed=seed,
               torsion_res=tres, theta_commutator_dev=theta_dev,
               n_freqs=len(coeffs))

    per, buggy = [], []
    all_levels, all_r = [], []
    for s in range(K):
        lam, B, m, cert = bc.multiplet_basis(U, K, chi, s, seed=seed)
        VL = B.conj().T @ bc.weyl_sum_operator(coeffs, N, B)
        VL = 0.5 * (VL + VL.conj().T)
        ev = np.linalg.eigvalsh(VL)
        per.append(dict(s=s, m=m, cert=cert,
                        ks_vs_full=ks(ev, full),
                        mom=moments_report(VL)))
        all_levels.append(ev)
        all_r.append(rtilde(ev))
    out["per_multiplet"] = per
    out["union_vs_full_res"] = float(np.max(np.abs(
        np.sort(np.concatenate(all_levels)) - full)))
    rr = np.concatenate([r for r in all_r if len(r)])
    out["rtilde_mean"] = float(rr.mean())
    out["rtilde_n"] = int(len(rr))
    out["rtilde_sem"] = float(rr.std(ddof=1) / math.sqrt(len(rr)))

    # classical (Weyl-law) comparison
    grid = min(N, 601)
    cls = bc.classical_symbol_values(cbar, N, grid=grid)
    out["ks_full_vs_classical"] = ks(full, cls)
    out["classical_std"] = float(cls.std())
    out["full_std"] = float(full.std())
    return out, U, chi, K, coeffs, full


def run29_reproduction(A, N, coeffs):
    """Reproduce run 29's construction: eigenvectors straight from
    numpy.linalg.eig on the unitary U, no orthonormalisation."""
    U = bc.U_cat(A, N)
    w, v = np.linalg.eig(U)
    from collections import Counter
    keys = Counter([(round(float(x.real), 5), round(float(x.imag), 5)) for x in w])
    key, _ = keys.most_common(1)[0]
    idxs = [i for i, x in enumerate(w) if abs(x - complex(*key)) < 1e-4]
    B = v[:, idxs]
    m = len(idxs)
    gram = B.conj().T @ B
    orth_dev = float(np.max(np.abs(gram - np.eye(m))))
    Id = np.eye(N, dtype=complex)
    V = bc.weyl_sum_observable = bc.weyl_sum_operator(coeffs, N, Id)
    V = 0.5 * (V + V.conj().T)
    W = B.conj().T @ (V @ B)
    W = W - np.trace(W) / m * np.eye(m)
    sv = np.linalg.svd(W, compute_uv=False)
    return dict(m=m, gram_dev=orth_dev,
                sv_max=float(sv[0]), sv_min=float(sv[-1]),
                sv_ratio=float(sv[0] / max(sv[-1], 1e-300)),
                mom=moments_report(0.5 * (W + W.conj().T)))


def controls(sizes, kind, seed=11, reps=1):
    """r-statistic on true GOE/GUE/Poisson spectra of the same block sizes."""
    rng = np.random.default_rng(seed)
    rr = []
    for _ in range(reps):
        for m in sizes:
            if kind == "goe":
                G = rng.standard_normal((m, m))
                H = (G + G.T) / math.sqrt(2)
                ev = np.linalg.eigvalsh(H)
            elif kind == "gue":
                G = (rng.standard_normal((m, m)) +
                     1j * rng.standard_normal((m, m))) / math.sqrt(2)
                H = (G + G.conj().T) / math.sqrt(2)
                ev = np.linalg.eigvalsh(H)
            else:
                ev = np.sort(rng.random(m))
            rr.append(rtilde(ev))
    rr = np.concatenate([r for r in rr if len(r)])
    return dict(kind=kind, mean=float(rr.mean()), n=int(len(rr)),
                sem=float(rr.std(ddof=1) / math.sqrt(len(rr))))


def main():
    configs = [((2, 1, 1, 1), 199), ((2, 1, 1, 1), 521), ((2, 1, 1, 1), 2207)]
    rows = []
    for A, N in configs:
        for mode in ("gen", "sym"):
            out, U, chi, K, coeffs, full = analyse(A, N, mode=mode)
            if mode == "gen":
                out["run29_repro"] = run29_reproduction(A, N, coeffs)
            sizes = [d["m"] for d in out["per_multiplet"]]
            out["control_goe"] = controls(sizes, "goe")
            out["control_gue"] = controls(sizes, "gue")
            out["control_poisson"] = controls(sizes, "poisson")
            rows.append(out)
            print(f"\n=== A={A} N={N} mode={mode} K={out['K']} "
                  f"m={sizes[0]}..{sizes[-1]} ===")
            print(f"  theta commutator dev      : {out['theta_commutator_dev']:.2e}")
            print(f"  union(multiplets) == spec : {out['union_vs_full_res']:.2e}")
            print(f"  KS(multiplet ESD, full)   : "
                  f"{np.mean([d['ks_vs_full'] for d in out['per_multiplet']]):.4f}")
            print(f"  KS(full, classical)       : {out['ks_full_vs_classical']:.4f}")
            print(f"  std full / classical      : {out['full_std']:.4f} / "
                  f"{out['classical_std']:.4f}")
            mm = out["per_multiplet"][0]["mom"]["rows"]
            print("  moment ratios vs Catalan  : " +
                  " ".join(f"{mm[j]['ratio_cat']:.2f}" for j in mm))
            print("  moment ratios vs Gaussian : " +
                  " ".join(f"{mm[j]['ratio_gauss']:.2f}" for j in mm))
            print(f"  <rtilde> = {out['rtilde_mean']:.4f} +- {out['rtilde_sem']:.4f}"
                  f"  (n={out['rtilde_n']})   GOE 0.5359 GUE 0.5996 Poisson 0.3863")
            print(f"     controls: GOE {out['control_goe']['mean']:.4f} "
                  f"GUE {out['control_gue']['mean']:.4f} "
                  f"Poisson {out['control_poisson']['mean']:.4f}")
            if "run29_repro" in out:
                r = out["run29_repro"]
                print(f"  [run29 repro] gram dev {r['gram_dev']:.3e}  "
                      f"sv ratio {r['sv_ratio']:.3e}  "
                      "ratios vs Catalan " +
                      " ".join(f"{r['mom']['rows'][j]['ratio_cat']:.2f}"
                               for j in r["mom"]["rows"]))
    os.makedirs(ART, exist_ok=True)
    with open(os.path.join(ART, "run42_esd.json"), "w") as f:
        json.dump(rows, f, indent=1, default=float)
    print("\nwrote artifacts/run42_esd.json")


if __name__ == "__main__":
    main()


