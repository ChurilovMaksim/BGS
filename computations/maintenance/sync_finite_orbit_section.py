#!/usr/bin/env python3
"""Render the maintained proof note to a manuscript section with Pandoc.

No mathematical source is generated by a model at execution time. The source
hash is embedded so stale manuscript output is detectable. --check is read-only.
"""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'mathematics/finite_orbit_resonance_rigidity.md'
TARGET=ROOT/'manuscript/unified_sections/finite_orbit_resonance.tex'

def render() -> str:
    source=SOURCE.read_text()
    # Publication formatting only; mathematical display content is unchanged.
    source=re.sub(r'^## [0-9]+\. ', '## ', source, flags=re.MULTILINE)
    result=subprocess.run(['pandoc','-f','markdown+tex_math_single_backslash',
        '-t','latex','--wrap=none'],input=source,text=True,capture_output=True,check=True)
    tex=result.stdout
    # Keep the statement and its displayed assertion on the same page.
    marker=r'\textbf{Theorem 1.}'
    if tex.count(marker)!=1:
        raise RuntimeError('finite-orbit theorem marker changed')
    tex=tex.replace(marker, r'\Needspace{12\baselineskip}'+'\n'+marker, 1)
    # xurl is already part of the repository's canonical manuscript preamble.
    tex=re.sub(r'\\texttt\{((?:mathematics|manuscript)/[^}]+)\}',
        lambda m:r'\path{'+m.group(1).replace(r'\_', '_')+'}',tex)
    sha=hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    return '% Generated by sync_finite_orbit_section.py; do not edit.\n'+ \
        '% Source SHA256: '+sha+'\n'+tex

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--check',action='store_true')
    args=ap.parse_args()
    output=render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text()!=output:
            sys.exit('finite-orbit manuscript section is stale')
        print('finite-orbit manuscript section matches canonical Markdown')
    else:
        TARGET.parent.mkdir(parents=True,exist_ok=True)
        TARGET.write_text(output)
        print(TARGET)
if __name__=='__main__':
    main()
