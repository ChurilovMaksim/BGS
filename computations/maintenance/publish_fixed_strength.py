ROOT=Path(__file__).resolve().parents[2]


def append_once(path: str, marker: str, addition: str) -> None:
    p=ROOT/path
    text=p.read_text()
    if marker not in text:
        p.write_text(text.rstrip()+'\n\n'+addition.strip()+'\n')


