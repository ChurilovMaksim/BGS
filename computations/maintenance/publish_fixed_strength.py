def main() -> None:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--integrate-only',action='store_true')
    args=p.parse_args();integrate()
    if not args.integrate_only:render()
    print('Locality sources registered; rendering does not imply validation.')

if __name__=='__main__':main()
