#!/usr/bin/env python3
"""Generate current proof navigation and the complete registered dependency view."""
from __future__ import annotations
import argparse
from collections import defaultdict, Counter
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
PREFIX="# Scientific corpus atlas\n\nGenerated by `computations/maintenance/render_research_views.py` from the\nclaim registry, topic map and proof headings. Do not edit this view by hand.\n\nLatest registered research update: **2026-10-19**. This is navigation,\nnot an independent proof review. The [claim ledger](../record/claim_ledger.md)\nexplains status changes; the registry controls registered status and covers fewer statements than the full corpus.\n\n## Start with the mathematical question\n\n| Reading task | Entry point |\n|---|---|\n| Exact deterministic family and microscopic target | [Model](../mathematics/fixed_map_resolvent_frontier.md), [trace bridge](../mathematics/trace_to_local_statistics_bridge.md) |\n| Current achievements and unresolved implications | [Research brief](../RESEARCH.md), [theorem index](../mathematics/results.md), [open questions](../mathematics/open_questions.md) |\n| Complete registered dependency structure | [Dependency view](../record/scientific_dependency_graph.md) |\n| Reproduce a result | [Reproduction guide](../REPRODUCE_unified.md), [computation guide](../computations/README.md) |\n| Understand source and execution boundaries | [Literature](../literature/README.md), [evidence](../evidence/README.md), [formalization](../formalization/README.md) |\n| Read or extract a publication | [Single manuscript](../manuscript/README.md), [focused candidate scopes](../papers/README.md) |\n| Trace a correction or previous route | [Research record](../record/README.md), [errata](../ERRATA.md), [historical index](../record/history/2026/INDEX.md) |\n\n![Distinct layers of scientific authority and evidence](../assets/figures/scientific_evidence_layers.svg)\n\nThe thematic branches below have different models, scales and hypotheses.\nThey are not a chain of implications to BGS. Historical input copies remain\nat their recorded paths; identical bytes can have different provenance.\n\n"
def esc(s): return s.replace('|',r'\|').replace('\n',' ')
def projections(root):
    data=json.loads((root/'record/claims.json').read_text()); rows=sorted(data['claims'],key=lambda r:r['id'])
    by={r['id']:r for r in rows}
    if len(by)!=len(rows): raise ValueError('Duplicate claim ID')
    active=set(); done=set()
    def visit(cid):
        if cid not in by: raise ValueError('Unknown prerequisite: '+cid)
        if cid in active: raise ValueError('Dependency cycle: '+cid)
        if cid in done:return
        active.add(cid)
        for dep in by[cid].get('dependencies',[]):visit(dep)
        active.remove(cid);done.add(cid)
    for cid in by:visit(cid)
    topics=json.loads((root/'record/mathematics_topics.json').read_text())['topics']
    registered={p for ps in topics.values() for p in ps}
    maintained={p.relative_to(root).as_posix() for p in (root/'mathematics').glob('*.md') if p.name not in {'README.md','results.md','results_20260907_addendum.md','open_questions.md'}}
    if registered!=maintained:raise ValueError('Topic map does not cover maintained proofs')
    sources=defaultdict(list);consumers=Counter()
    for row in rows:
        sources[row['source']].append(row);consumers.update(row.get('dependencies',[]))
    out=[PREFIX.replace('2026-10-19',data['updated']).rstrip(),'',
         '## Registered state and complete proof navigation','',
         f"**{len(registered)} maintained proof notes; {len(topics)} topic views; {len(rows)} core claim IDs.**",'',
         '| Core registry state | IDs |','|---|---:|']
    for state,n in sorted(Counter(r['state'] for r in rows).items()):out.append(f'| {state} | {n} |')
    out+=['','“Proved” reports the project registry at its stated scope, not external refereeing.',
          'No state is inferred for an unregistered note. Read its proof and the full ledger.','']
    for topic,paths in topics.items():
        name=(root/'mathematics/topics'/topic/'README.md').read_text().splitlines()[0].removeprefix('# ')
        out += [f'### {esc(name)}','',f'[Reading sequence](../mathematics/topics/{topic}/README.md) · {len(set(paths))} notes','',
                '| Canonical proof source | Core IDs and registered states |','|---|---|']
        for rel in sorted(set(paths)):
            title=next((s[2:] for s in (root/rel).read_text().splitlines() if s.startswith('# ')),Path(rel).stem)
            ids='; '.join(f"`{r['id']}` ({r['state']})" for r in sources[rel]) or 'Consult proof and full ledger'
            out.append(f'| [{esc(title)}](../{rel}) | {ids} |')
        out.append('')
    edges=sorted({(dep,r['id']) for r in rows for dep in r.get('dependencies',[])})
    graph={'schema':'bgs-scientific-dependencies-v1','updated':data['updated'],'nodes':sorted(by),
           'edges':[{'from':d,'to':c,'type':'scientific-prerequisite'} for d,c in edges],
           'terminal_open_claims':[r['id'] for r in rows if r['state']=='open'],
           'note':'Generated from record/claims.json; registered programme prerequisites, not every lemma or proof of a downstream claim.'}
    view=['# Scientific dependency graph','',
          'Generated from [claims.json](claims.json) by `computations/maintenance/render_research_views.py`.',
          'The [registry](claims.json) controls registered status; the [ledger](claim_ledger.md) explains changes. The JSON view has the same complete adjacency.','',
          f"**{len(rows)} registered nodes; {len(edges)} direct prerequisite edges.**",'',
          'An edge records a scoped programme prerequisite; it does not discharge a hypothesis.',
          '“None registered” does not mean unconditional or self-contained.',
          'External locators and mappings are in the [external registry](../literature/external_dependencies.json).','',
          'BGS-BGS-001 and BGS-TRACE-005 remain OPEN. Auxiliary ensembles and',
          'abstract-family obstructions retain their original models and proof boundaries.','',
          '| Claim and source | State | Direct registered prerequisites | Registered external inputs | Direct consumers |',
          '|---|---|---|---|---:|']
    for r in rows:
        ds=', '.join('`'+s+'`' for s in sorted(r.get('dependencies',[]))) or 'None registered'
        es=', '.join('`'+s+'`' for s in sorted(r.get('external_dependencies',[]))) or 'None registered'
        view.append(f"| [{r['id']}](../{r['source']}) | {r['state']} | {ds} | {es} | {consumers[r['id']]} |")
    return {'docs/corpus_atlas.md':'\n'.join(out).rstrip()+'\n',
            'record/scientific_dependencies.json':json.dumps(graph,indent=2)+'\n',
            'record/scientific_dependency_graph.md':'\n'.join(view)+'\n'}
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,default=ROOT);p.add_argument('--check',action='store_true');a=p.parse_args()
    stale=[]
    for rel,text in projections(a.root).items():
        path=a.root/rel
        if a.check:
            if not path.is_file() or path.read_text()!=text:stale.append(rel)
        else:path.write_text(text)
    if stale:p.exit(1,'Research navigation drift: '+', '.join(stale)+'\n')
    print('Research navigation views synchronized')
if __name__=='__main__':main()
