#!/usr/bin/env python3
"""Summarize successful raw checks without changing their provenance.

Raw reports and logs are supplied in the research archive or regenerated by
the documented commands. Only their compact hash-index is stored in main.
"""
from pathlib import Path
import hashlib
import json

ROOT=Path(__file__).resolve().parents[2]
EVIDENCE=ROOT/'evidence'

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def load(name):
    return json.loads((EVIDENCE/name).read_text())

def main():
    reports={n:load(n) for n in ('sharp_coercivity.json','four_mode_coercivity.json',
                                'flat_quantum.json','flat_quantum_large.json')}
    for report in reports.values():
        assert report['status']=='PASS'
        assert digest(ROOT/report['producer'])==report['source_sha256']
    labels=('cpp_compile','sharp_variational','four_mode','quantum_core','quantum_1023')
    executions=[]
    for label in labels:
        p=EVIDENCE/(label+'_execution.json');r=json.loads(p.read_text())
        assert r['returncode']==0 and r['sources_unchanged']
        assert digest(ROOT/r['log'])==r['log_sha256']
        executions.append({'label':label,'returncode':0,'elapsed_seconds':r['elapsed_seconds'],
                           'record_sha256':digest(p),'log_sha256':r['log_sha256']})
    cpp='computations/cpp/pell_sharp_orbit_verifier.cpp'
    assert digest(ROOT/cpp)==load('cpp_compile_execution.json')['source_sha256'][cpp]
    sharp=reports['sharp_coercivity.json'];four=reports['four_mode_coercivity.json']
    flat=reports['flat_quantum.json'];large=reports['flat_quantum_large.json']
    assert sharp['cpp_crosscheck']==four['cpp_crosscheck']=='PASS'
    values=[]
    for r in flat['flat']+large['flat']:
        item=next(x for x in r['checks'] if x['kappa']==.02)
        values.append({'N':r['N'],'kappa':.02,'commutator_operator_norm':r['commutator_operator_norm'],
                       'gauge_operator_error':item['gauge_operator_error']})
    data={'status':'TARGETED_CHECKS_PASS',
          'scope':'Finite exact and floating-point checks; no global CI, new Lean build, external proof acceptance or priority inferred.',
          'read_base':'ae01ae4585f86de0c97b00d165abf6cd9f11d999',
          'single_orbit_exact_cases':sharp['exact_cases'],'other_maps':sharp['other_hyperbolic_maps'],
          'rational_optimizer_count':len(sharp['rational_optimizers']),
          'sample_spectral_factor_count':len(sharp['sample_factors']),
          'four_mode_coefficient_identity':'exact polynomial equality and sum of squares over Z',
          'four_mode_cpp_cases':len(four['integer_rows']),
          'radius_three_witness':{k:v for k,v in four['radius_three_witness'].items() if k!='nonzero_orbit_sums'},
          'support':flat['support'],'algebra':flat['algebra'],
          'classical_checks':len(flat['classical']['checks']),
          'classical_max_error':max(r['error'] for r in flat['classical']['checks']),
          'classical_nonzero_displacement':flat['classical']['maximum_displacement'],
          'wrong_sign_negative_control':flat['classical']['wrong_sign_negative_control'],
          'analytic_commutator_checks':flat['analytic'],'flat_operator_checks':values,
          'pell_kick_cases':len(flat['pell_spectra']),
          'report_sha256':{n:digest(EVIDENCE/n) for n in reports},
          'checked_code_sha256':{p:digest(ROOT/p) for p in sorted({cpp}|{r['producer'] for r in reports.values()})},
          'executions':executions,
          'excluded_attempts':['N=1023,2047 combined run timed out; no N=2047 result.',
              'No local Lean compiler available; no new Lean build claimed.',
              'Radius-two/radius-three numerical optimization and restricted LP infeasibility are not global theorems.'],
          'rounding':'No outward interval rounding for matrix/ODE/root calculations. Exact combinatorics and rational identities are separately scoped.'}
    dst=EVIDENCE/'rigidity_validation.json'
    dst.write_text(json.dumps(data,indent=2)+'\n')
    print(dst)

if __name__=='__main__':main()
