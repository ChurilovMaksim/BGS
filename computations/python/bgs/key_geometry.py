"""Exact finite pair-key geometry for the corrected fourth-moment reduction.

For x,y outside {0,1}, set

    u=x/y,  v=(x-1)/(y-1),  d=x-y.

Off the diagonal the map is bijective onto u,v in F_p^*\{1}, u!=v.
The diagonal collapses to (1,1), difference zero, with multiplicity p-2.
This module contains finite combinatorics only; it asserts no BGS limit law.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .finite_field import require_odd_prime


@dataclass(frozen=True, slots=True)
class KeyRecord:
    """One collapsed key-table record."""

    u: int
    v: int
    difference: int
    multiplicity: int = 1

    @property
    def is_diagonal(self) -> bool:
        return self.u == 1 and self.v == 1


def subgroup_elements(prime: int, generator: int, order: int) -> np.ndarray:
    """Return the exact order-``order`` subgroup generated by ``generator``."""
    require_odd_prime(prime)
    if order <= 0 or (prime - 1) % order:
        raise ValueError("order must be a positive divisor of prime-1")
    generator %= prime
    if generator == 0:
        raise ValueError("subgroup generator must be nonzero")

    values: list[int] = []
    value = 1
    for _ in range(order):
        if value in values:
            raise ValueError(
                f"generator {generator} has order smaller than {order} modulo {prime}"
            )
        values.append(value)
        value = value * generator % prime
    if value != 1:
        raise ValueError(
            f"generator {generator} does not have order {order} modulo {prime}"
        )
    return np.array(sorted(values), dtype=np.int64)


def inverse_table(prime: int) -> np.ndarray:
    """Return modular inverses on F_p^*, leaving entry zero equal to zero."""
    require_odd_prime(prime)
    inverses = np.zeros(prime, dtype=np.int64)
    inverses[1:] = [pow(value, prime - 2, prime) for value in range(1, prime)]
    return inverses


def key_difference(prime: int, u: int, v: int) -> int:
    """Return d(u,v)=(u-1)(v-1)/(v-u) on the off-diagonal key domain."""
    require_odd_prime(prime)
    u %= prime
    v %= prime
    if u in (0, 1) or v in (0, 1) or u == v:
        raise ValueError("key_difference requires u,v in F_p^*\\{1}, u!=v")
    return (u - 1) * (v - 1) * pow((v - u) % prime, prime - 2, prime) % prime


def explicit_key_table(prime: int) -> list[KeyRecord]:
    """Build the collapsed key table from its explicit image description."""
    require_odd_prime(prime)
    records = [KeyRecord(1, 1, 0, prime - 2)]
    for u in range(2, prime):
        for v in range(2, prime):
            if u != v:
                records.append(KeyRecord(u, v, key_difference(prime, u, v), 1))
    return records


def original_pair_key_table(prime: int) -> list[KeyRecord]:
    """Collapse original (x,y) pairs; independent small-p validation path."""
    require_odd_prime(prime)
    records: dict[tuple[int, int], KeyRecord] = {}
    for x in range(2, prime):
        for y in range(2, prime):
            u = x * pow(y, prime - 2, prime) % prime
            v = (x - 1) * pow(y - 1, prime - 2, prime) % prime
            difference = (x - y) % prime
            key = (u, v)
            previous = records.get(key)
            if previous is None:
                records[key] = KeyRecord(u, v, difference, 1)
            else:
                if key != (1, 1) or previous.difference or difference:
                    raise AssertionError(f"unexpected repeated off-diagonal key {key}")
                records[key] = KeyRecord(1, 1, 0, previous.multiplicity + 1)

    diagonal = records.get((1, 1))
    if diagonal is None or diagonal.multiplicity != prime - 2:
        raise AssertionError("original-pair collapse has wrong diagonal multiplicity")
    return list(records.values())


def records_as_map(records: list[KeyRecord]) -> dict[tuple[int, int], KeyRecord]:
    """Index records by key, rejecting accidental duplicates."""
    out = {(record.u, record.v): record for record in records}
    if len(out) != len(records):
        raise ValueError("duplicate collapsed key records")
    return out


def _validate_subgroup_array(prime: int, subgroup: np.ndarray) -> None:
    require_odd_prime(prime)
    values = [int(x) % prime for x in subgroup.tolist()]
    if not values or len(set(values)) != len(values) or 1 not in values:
        raise ValueError("subgroup array must contain distinct residues including 1")
    value_set = set(values)
    if any((x * y) % prime not in value_set for x in values for y in values):
        raise ValueError("subgroup array is not multiplicatively closed")


def direct_difference_distribution(
    prime: int,
    subgroup: np.ndarray,
    records: list[KeyRecord],
) -> tuple[np.ndarray, dict[str, int]]:
    """Compute B(t) by an explicit ordered loop over collapsed key records."""
    _validate_subgroup_array(prime, subgroup)
    in_subgroup = np.zeros(prime, dtype=bool)
    in_subgroup[subgroup] = True
    distribution = np.zeros(prime, dtype=np.int64)
    classes = {
        "off_to_off": 0,
        "diagonal_to_off": 0,
        "off_to_diagonal": 0,
        "diagonal_to_diagonal": 0,
    }

    for left in records:
        for right in records:
            if not in_subgroup[left.u * right.u % prime]:
                continue
            if not in_subgroup[left.v * right.v % prime]:
                continue
            weight = left.multiplicity * right.multiplicity
            distribution[(left.difference + right.difference) % prime] += weight
            if left.is_diagonal and right.is_diagonal:
                classes["diagonal_to_diagonal"] += weight
            elif left.is_diagonal:
                classes["diagonal_to_off"] += weight
            elif right.is_diagonal:
                classes["off_to_diagonal"] += weight
            else:
                classes["off_to_off"] += weight
    return distribution, classes


def fast_difference_distribution(
    prime: int,
    subgroup: np.ndarray,
) -> tuple[np.ndarray, dict[str, int]]:
    """Compute B(t) in O(K^2 p^2) using the corrected H^2 partner map.

    The diagonal key is not inserted into the off-diagonal grid. The two
    ordered mixed classes are added separately, preventing the historical
    factor-of-two regression.
    """
    _validate_subgroup_array(prime, subgroup)
    values = np.arange(2, prime, dtype=np.int64)
    inverses = inverse_table(prime)

    u_grid = values[:, None]
    v_grid = values[None, :]
    valid = u_grid != v_grid
    difference = np.full((prime - 2, prime - 2), -1, dtype=np.int64)
    numerator = (u_grid - 1) * (v_grid - 1) % prime
    denominator = (v_grid - u_grid) % prime
    difference[valid] = numerator[valid] * inverses[denominator[valid]] % prime

    lookup = np.full((prime, prime), -1, dtype=np.int64)
    lookup[np.ix_(values, values)] = difference

    distribution = np.zeros(prime, dtype=np.int64)
    off_to_off = 0
    subgroup_values = [int(x) for x in subgroup.tolist()]
    for h1 in subgroup_values:
        partner_u = h1 * inverses[values] % prime
        for h2 in subgroup_values:
            partner_v = h2 * inverses[values] % prime
            partner_difference = lookup[partner_u[:, None], partner_v[None, :]]
            both_valid = valid & (partner_difference >= 0)
            targets = (difference + partner_difference) % prime
            selected = targets[both_valid]
            np.add.at(distribution, selected, 1)
            off_to_off += int(selected.size)

    mixed_histogram = np.zeros(prime, dtype=np.int64)
    nonidentity = [value for value in subgroup_values if value != 1]
    for u in nonidentity:
        for v in nonidentity:
            if u != v:
                mixed_histogram[key_difference(prime, u, v)] += 1

    diagonal_weight = prime - 2
    distribution += 2 * diagonal_weight * mixed_histogram
    distribution[0] += diagonal_weight**2

    mixed_total = diagonal_weight * int(mixed_histogram.sum())
    classes = {
        "off_to_off": off_to_off,
        "diagonal_to_off": mixed_total,
        "off_to_diagonal": mixed_total,
        "diagonal_to_diagonal": diagonal_weight**2,
    }
    return distribution, classes


def expected_coupling_classes(prime: int, subgroup_order: int) -> dict[str, int]:
    """Return the exact four coupling-class totals."""
    require_odd_prime(prime)
    if subgroup_order <= 0 or (prime - 1) % subgroup_order:
        raise ValueError("subgroup_order must divide prime-1")
    diagonal_weight = prime - 2
    mixed = diagonal_weight * (subgroup_order - 1) * (subgroup_order - 2)
    off = (
        subgroup_order**2 * (prime - 2) * (prime - 3)
        - 3 * subgroup_order * (subgroup_order - 1) * (prime - 3)
        + 2 * (subgroup_order - 1) * (subgroup_order - 2)
    )
    return {
        "off_to_off": off,
        "diagonal_to_off": mixed,
        "off_to_diagonal": mixed,
        "diagonal_to_diagonal": diagonal_weight**2,
    }


def variety_count_formula(prime: int, subgroup_order: int) -> int:
    """Return the exact closed form for |V4|."""
    classes = expected_coupling_classes(prime, subgroup_order)
    total_from_classes = sum(classes.values())
    n = prime
    k = subgroup_order
    closed = (k * k + 1) * n * n - (6 * k * k + 3 * k) * n + 13 * k * k - 3 * k
    if total_from_classes != closed:
        raise AssertionError("coupling-class sum disagrees with V4 closed form")
    return closed
