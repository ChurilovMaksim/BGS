"""Independent referee engine for Line D (written from scratch; shares no code with bgs-lineD/code)."""

if not __debug__:
    raise RuntimeError('Verification requires assertions; run Python without -O/-OO or PYTHONOPTIMIZE.')

import numpy as np
from math import gcd
from functools import reduce

def pell(m):
    """S^m = [[x,4y],[2y,x]] for S=[[3,4],[2,3]]: returns (x,y) as Python ints."""
    x, y = 1, 0
    for _ in range(m):
        x, y = 3*x + 8*y, x + 3*y
    return x, y

def Hmat(m):
    H = np.zeros((m, m), dtype=object)
    for i in range(m):
        H[i, i] += 6
        H[i, (i+1) % m] -= 1
        H[(i+1) % m, i] -= 1
    return H

def det_int(M):
    import sympy
    return int(sympy.Matrix(M.tolist()).det())

def adj_int(M):
    import sympy
    A = sympy.Matrix(M.tolist()).adjugate()
    return np.array(A.tolist(), dtype=object)

def data(m):
    H = Hmat(m)
    D = det_int(H)
    X = adj_int(H)          # X = D H^{-1}, integer (adjugate)
    assert (H.dot(X) == D*np.eye(m, dtype=object)).all()
    x, y = pell(m)
    assert D == 2*x - 2, (D, x)   # D = Tr S^m - 2
    # A(n) = 2 n^T X n ; reduced modulus g' = D / gcd(D, all coefficients of A as integer quadratic form)
    coeffs = [2*X[i, i] for i in range(m)] + [4*X[i, j] for i in range(m) for j in range(i+1, m)]
    g = reduce(gcd, [int(c) for c in coeffs] + [D])
    return dict(m=m, H=H, D=D, X=X, gp=D//g)

# ---------------------------------------------------------------- brute force side
def Mp(p):
    inv8 = pow(8, -1, p)
    x = np.arange(p)
    Q = (3*x[:, None]**2 - 2*x[:, None]*x[None, :] + 3*x[None, :]**2) % p
    ph = (-inv8 * Q) % p
    return np.exp(2j*np.pi*ph/p) / np.sqrt(p)

def trace_powers(U, mmax):
    out = {}
    P = np.eye(U.shape[0], dtype=complex)
    for m in range(1, mmax+1):
        P = P @ U
        out[m] = np.trace(P)
    return out

# ---------------------------------------------------------------- group side
def enum_fix(dat):
    """Fix_m = H^{-1}Z^m/Z^m, represented as integer vectors w mod D (xi = w/D).
    BFS on the subgroup of (Z/D)^m generated by the columns of X mod D."""
    m, D, X = dat['m'], dat['D'], dat['X']
    gens = [tuple(int(X[i, j]) % D for i in range(m)) for j in range(m)]
    seen = {tuple([0]*m)}
    frontier = [tuple([0]*m)]
    while frontier:
        new = []
        for v in frontier:
            for g in gens:
                w = tuple((a+b) % D for a, b in zip(v, g))
                if w not in seen:
                    seen.add(w); new.append(w)
        frontier = new
    W = np.array(sorted(seen), dtype=np.int64)
    assert len(W) == D, (len(W), D)
    return W

def enum_V(dat):
    """V = Z^m / H Z^m: integer representatives beta, keyed by X beta mod D (injective)."""
    m, D, X = dat['m'], dat['D'], dat['X']
    Xi = np.array(X, dtype=np.int64)
    start = tuple([0]*m)
    key = lambda b: tuple((Xi @ np.array(b)) % D)
    seen = {key(start): start}
    frontier = [start]
    while frontier:
        new = []
        for b in frontier:
            for i in range(m):
                for sgn in (1,):
                    bb = list(b); bb[i] += sgn; bb = tuple(bb)
                    k = key(bb)
                    if k not in seen:
                        seen[k] = bb; new.append(bb)
        frontier = new
    B = np.array(list(seen.values()), dtype=np.int64)
    assert len(B) == D
    return B

def phihat(dat, s, W, B, chunk=200):
    """phihat_s(xi) = D^{-1} sum_{beta in V} e(2 s beta^T H^{-1} beta - beta.xi), xi = w/D.
    Exact integer phases mod D."""
    D = dat['D']; Xi = np.array(dat['X'], dtype=np.int64)
    q = (2*s*np.einsum('bi,ij,bj->b', B, Xi, B)) % D          # 2 s beta^T X beta  (mod D)
    tab = np.exp(2j*np.pi*np.arange(D)/D)
    out = np.zeros(len(W), dtype=complex)
    for i0 in range(0, len(W), chunk):
        w = W[i0:i0+chunk]
        ph = (q[None, :] - (w @ B.T) % D) % D
        out[i0:i0+chunk] = tab[ph].sum(axis=1) / D
    return out

def gamma_canon(W, D):
    """canonical representative of the dihedral (shift+reversal) class of each row; returns labels and class sizes"""
    m = W.shape[1]
    imgs = []
    for r in range(m):
        sh = np.roll(W, r, axis=1)
        imgs.append(sh); imgs.append(sh[:, ::-1])
    keys = [ [tuple(row) for row in im] for im in imgs ]
    canon = [min(k[i] for k in keys) for i in range(len(W))]
    orbsize = [len(set(k[i] for k in keys)) for i in range(len(W))]
    return canon, np.array(orbsize)

def Sk(W, D, k):
    return np.exp(2j*np.pi*k*W/D).sum(axis=1)
