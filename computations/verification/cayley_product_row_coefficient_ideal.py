#!/usr/bin/env python3
"""Exact finite regression for cayley_product_row_coefficient_ideal.md.

The script reuses the maintained product-row/subresultant construction and then
forms the coefficient ideal J in Z[zeta_K].  Multiplication by powers of zeta
turns its generators into a full integer lattice.  The Smith normal form of
that lattice presents O_L/J; its largest invariant factor is the positive
generator of J intersect Z, equivalently the additive exponent of O_L/J.

Default anchors are deliberately small enough for CI.  ``--extended`` adds the
slower K=17 case.  No finite run proves the growing-K split-prime bound.
"""
from __future__ import annotations

import argparse

import sympy as sp
from sympy.matrices.normalforms import smith_normal_form

from cayley_product_row_subresultants import (
    X,
    reduce_cyclotomic,
    strip_2K,
    subresultants_in_cyclotomic_ring,
)


def coefficient_vector(K: int, expr: sp.Expr) -> list[int]:
    """Coordinates in the integral basis 1,X,...,X^(K-2) modulo Phi_K."""
    reduced = sp.Poly(reduce_cyclotomic(expr, K), X, domain=sp.ZZ)
    return [int(reduced.nth(j)) for j in range(K - 1)]


def selected_coefficients(K: int, r: int) -> list[sp.Expr]:
    """Return all nonzero coefficients of the degree 2,1,0 subresultants."""
    if K < 7:
        raise ValueError("three-subresultant integral construction requires K>=7")
    subs = subresultants_in_cyclotomic_ring(K, r)
    selected = subs[-3:]
    assert [poly.degree() for poly in selected] == [2, 1, 0], (K, r)
    coeffs: list[sp.Expr] = []
    for poly in selected:
        for coeff in poly.all_coeffs():
            coeff = reduce_cyclotomic(coeff, K)
            if coeff != 0:
                coeffs.append(coeff)
    assert coeffs
    return coeffs


def coefficient_ideal_exponent(K: int, r: int) -> tuple[int, int, list[int]]:
    """Return (D with 2,K stripped, full D, nonzero Smith invariants)."""
    columns: list[sp.Matrix] = []
    for coeff in selected_coefficients(K, r):
        # The Z-lattice of the O_L-ideal generated by coeff is spanned by
        # zeta^j*coeff, 0<=j<K-1.  Reducing modulo Phi_K gives coordinates in
        # the standard integral basis of the prime cyclotomic ring.
        for j in range(K - 1):
            columns.append(sp.Matrix(coefficient_vector(K, coeff * X**j)))

    lattice = sp.Matrix.hstack(*columns)
    assert lattice.rows == K - 1
    smith = smith_normal_form(lattice, domain=sp.ZZ)
    invariants = [
        abs(int(smith[j, j]))
        for j in range(min(smith.rows, smith.cols))
        if smith[j, j] != 0
    ]
    # J is a nonzero ideal of the degree-(K-1) number field, hence full rank.
    assert len(invariants) == K - 1, (K, r, len(invariants))
    assert all(invariants[j + 1] % invariants[j] == 0 for j in range(len(invariants) - 1))

    full_D = invariants[-1]
    return strip_2K(full_D, K), full_D, invariants


def prime_to_2K_order_three_support(K: int, r: int) -> int:
    """Coarse support including trivial small orders, without fictitious ideals."""
    if not sp.isprime(K) or K == 2 or not 2 <= r < K:
        raise ValueError("require odd prime K and normalized 2<=r<K")
    if K in (3, 5):
        return 1
    return coefficient_ideal_exponent(K, r)[0]


def check_anchor(K: int, r: int, expected_stripped: int, expected_full: int) -> None:
    stripped, full_D, invariants = coefficient_ideal_exponent(K, r)
    assert stripped == expected_stripped, (K, r, stripped, expected_stripped)
    assert full_D == expected_full, (K, r, full_D, expected_full)
    print(
        f"K={K:2d} r={r:2d} D3={full_D} D3'={stripped} "
        f"smith_rank={len(invariants)}"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--extended", action="store_true")
    args = parser.parse_args()

    for K in (3, 5):
        for r in range(2, K):
            assert prime_to_2K_order_three_support(K, r) == 1

    for K, r, stripped, full_D in (
        (7, 2, 1, 2 * 7**2),
        (11, 2, 1, 2 * 11**4),
        (13, 3, 3, 2 * 3 * 13**6),
        (13, 12, 5**2, 2**5 * 5**2 * 13**6),
    ):
        check_anchor(K, r, stripped, full_D)

    if args.extended:
        check_anchor(17, 10, 103, 2**2 * 17**9 * 103)

    print("cayley product-row coefficient-ideal regression: OK")


if __name__ == "__main__":
    main()
