def dihedral_perms(m):
    perms = []
    for b in range(m):
        perms.append(('rot', b, tuple((j + b) % m for j in range(m))))
        perms.append(('refl', b, tuple((b - j) % m for j in range(m))))
    return perms

def stabilisers(v, m):
    out = []
    for kind, b, p in dihedral_perms(m):
        if tuple(v[p[j]] for j in range(m)) == v:
            out.append((kind, b))
    return out

def orbit_partition(stab, m):
    # partition of positions into orbits under group generated by stab
    # (stab is a subgroup; here stabiliser is order 1 or 2, generated by
    # one element if nontrivial)
    parent = list(range(m))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x
    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb: parent[ra] = rb
    for kind, b in stab:
        if kind == 'rot':
            p = [(j + b) % m for j in range(m)]
        else:
            p = [(b - j) % m for j in range(m)]
        for j in range(m):
            union(j, p[j])
    blocks = {}
    for j in range(m):
        blocks.setdefault(find(j), []).append(j)
    return sorted(tuple(sorted(v)) for v in blocks.values())

def value_partition(v):
    blocks = {}
    for j, val in enumerate(v):
        blocks.setdefault(val, []).append(j)
    return sorted(tuple(sorted(v)) for v in blocks.values())

def report_component(m, q, vecs):
    res = {"m": m, "q": q, "n": len(vecs)}
    # distinct value counts
    res["distinct_value_count_dist"] = {str(k): v for k, v in sorted(Counter(len(set(v)) for v in vecs).items())}
    # stabiliser types
    stab_dist = Counter()
    part_match = Counter()
    examples_mismatch = []
    for v in vecs:
        stab = stabilisers(v, m)
        # stabiliser as set; classify: trivial, rotation-only, reflection
        kinds = [k for k, _ in stab]
        if len(stab) == 1:
            typ = "trivial"
        elif 'refl' in kinds:
            typ = "reflection"
        else:
            typ = "rotation"
        stab_dist[typ] += 1
        vp = value_partition(v)
        op = orbit_partition(stab, m)
        match = (vp == op)
        part_match[(typ, match)] += 1
        if not match and len(examples_mismatch) < 3:
            examples_mismatch.append({"v": list(v), "stab": stab, "value_partition": vp, "orbit_partition": op})
    res["stabiliser_dist"] = dict(stab_dist)
    res["partition_match"] = {f"{k[0]}:{k[1]}": v for k, v in part_match.items()}
    res["mismatch_examples"] = examples_mismatch
    return res

