def find_orbit_H(p, A):
    """Find subgroup H of F_p^x generated by alpha where alpha comes from
    eigenvalues of A mod p. Returns sorted list H."""
    a,b,c,d = A
    tr = (a+d) % p; det = (a*d-b*c) % p
    disc = (tr*tr - 4*det) % p
    if disc == 0: return None
    # sqrt of disc mod p via Tonelli-Shanks or sympy
    from sympy.ntheory.residue_ntheory import sqrt_mod_iter
    roots = list(sqrt_mod_iter(disc, p))
    if not roots: return None  # inert case
    r = int(roots[0])
    alpha = ((tr + r) * pow(2, -1, p)) % p
    if alpha == 0: return None
    # orbit of alpha: {alpha, alpha^2, ..., alpha^(d-1), alpha^d=1}
    # We want the FULL subgroup including 1, so add it explicitly.
    Hset, x = [], alpha % p
    while x != 1:
        Hset.append(x); x = x*alpha % p
    Hset.append(1)   # include identity element
    return sorted(set(Hset))


def brute_resonance_solutions(p, H, signs=(+1,-1,+1,-1)):
    """All (h1..h4) in H^4 satisfying two-component resonance."""
    inv = {h: pow(h,p-2,p) for h in H}
    L = {}
    Hlist = sorted(H)
    for h1 in Hlist:
        s1 = signs[0]*h1 % p; t1 = signs[0]*inv[h1] % p
        for h3 in Hlist:
            kk = ((s1+signs[2]*h3)%p, (t1+signs[2]*inv[h3])%p)
            L.setdefault(kk,[]).append((h1,h3))
    sols=[]
    for h2 in Hlist:
        s2 = signs[1]*h2 % p; t2 = signs[1]*inv[h2] % p
        for h4 in Hlist:
            need = ((-(s2+signs[3]*h4))%p, -(t2+signs[3]*inv[h4])%p)
            if need in L:
                for (h1,h3) in L[need]: sols.append((h1,h2,h3,h4))
    return sols


